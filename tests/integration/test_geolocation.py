"""Geolocation through the whole kernel chain, from the frozen dynamic kernels.

These tests consume the committed kernels in ``tests/test_data/dynamic_kernels`` rather than
building their own, mirroring production: the L1B container is handed kernels from S3 and
never generates them. Kernel *generation* is covered separately by the kernel-maker tests, and
each frozen kernel is checked against its source in
``tests/unit/test_libera_spice/test_frozen_kernels.py``.

The fixture is regenerated by ``tests/fixture_generation/generate_dynamic_kernels.py`` from
the Jake Fernandez CSVs under ``tests/test_data/tier1_geo``, and covers a 60 s window centred
on closest approach to the Libya-4 calibration site during a simulated JPSS-4 overpass.

Assertion strategy: the geolocation checks here are deliberately loose, because near the limb
the ground intersection is extremely sensitive to sub-arcminute pointing changes and any tight
footprint bound would be fragile across platforms. Precision belongs at the step level, in the
unit tests; tolerance at the end-to-end level, here.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest
from curryer import spicetime
from curryer import spicierpy as sp
from curryer.compute import constants, spatial

from libera_utils import kernel_maker
from libera_utils.config import config
from libera_utils.libera_spice import spice_utils
from tests.fixture_generation import generate_dynamic_kernels as fixture_gen
from tests.plugins.spice_fixtures import LIBYA4_LAT_DEG, LIBYA4_LON_DEG, NOMINAL_AZ_AXIS, NOMINAL_EL_AXIS

pytestmark = pytest.mark.integration


def test_frozen_kernels_geolocate_the_scan_over_libya4(frozen_kernel_manager):
    """Geolocating the frozen kernels puts the cross-track scan across the Libya-4 site.

    Validation provenance
    ---------------------
    This is the test that satisfies the **Tier-1 geolocation** internal validation: the simulated
    JPSS-4 overpass of Libya-4 and its quality-flag bound, with the footprint checked as proximity
    to the site. It must not be loosened without re-running that validation.

    The end-to-end check: static offsets, spacecraft ephemeris and attitude, both mechanism CKs
    and the frame kernel compose into a ground track over the intended target. The tolerance is
    loose by design -- the assertion is "the scan crosses the site", not a pinned footprint,
    because near the limb the intersection is acutely sensitive to sub-arcminute pointing and a
    tight bound would be fragile. The exact mechanism and spacecraft geometry is pinned by
    ``tests/unit/test_libera_spice/test_frozen_kernels.py``.
    """
    times = pd.date_range(fixture_gen.WINDOW_START, fixture_gen.WINDOW_END, freq="10ms", inclusive="left")
    lla, _, quality_flags = spatial.compute_ellipsoid_intersection(
        spicetime.adapt(times, "iso"),
        sp.obj.Body("LIBERA_RAD", frame=True),
        give_geodetic_output=True,
        give_lat_lon_in_degrees=True,
    )

    # Most samples intersect the ellipsoid; the rest are the wide cross-track scan grazing the
    # limb, which is expected geometry rather than a failure. The 0.78 bound is the Tier-1
    # validation's, and the 60 s window meets it because limb grazing comes from the +/-72 deg
    # sweep, not from the length of the window. The margin is small (0.7882 measured), so a
    # platform difference that moves the limb samples can fail this before anything else.
    good_fraction = (quality_flags == 0).sum() / len(quality_flags)
    assert good_fraction >= 0.78, good_fraction

    latitude = lla["lat"].to_numpy()
    longitude = lla["lon"].to_numpy()
    finite = np.isfinite(latitude) & np.isfinite(longitude)
    assert finite.any(), "No sample intersected the ellipsoid"

    site_lat, site_lon = np.deg2rad(LIBYA4_LAT_DEG), np.deg2rad(LIBYA4_LON_DEG)
    sample_lat, sample_lon = np.deg2rad(latitude[finite]), np.deg2rad(longitude[finite])
    haversine = (
        1 - np.cos(sample_lat - site_lat) + np.cos(site_lat) * np.cos(sample_lat) * (1 - np.cos(sample_lon - site_lon))
    ) / 2
    distance_km = 2 * constants.WGS84_SEMI_MAJOR_AXIS_KM * np.arcsin(np.sqrt(haversine))

    # The scan sweeps +/-72 deg across the site, so some sample lands very near it. The bound is
    # set by how coarsely the fast sweep samples the ground, not by pointing accuracy.
    assert distance_km.min() < 10.0, (
        f"Closest sample is {distance_km.min():.3f} km from Libya-4; the scan does not cross the site"
    )


def test_measured_misalignment_shifts_the_geolocated_footprint(
    frozen_kernel_manager, curryer_lsk, nominal_frame_kernel, short_tmp_path
):
    """The measured misalignment changes where the scan lands on the ground.

    Validation provenance
    ---------------------
    This is the test that satisfies the **Tier-1 misalignment A/B** internal validation. It
    geolocates the same scan twice from one spacecraft state -- once with the measured axes and boresight, once with the
    ideal orthogonal gimbal -- and requires every footprint to move by at least the ground distance
    the smallest measured axis tilt subtends from orbit.

    The measured leg reuses the frozen fixture; only the nominal leg is built here, from the same
    source rows via the fixture generator's own frame builders, so the two configurations differ
    in geometry alone and not in sampling, window, or input data. Differencing within one run also
    cancels common-mode platform geometry, which is what keeps the check deterministic across
    msopck builds where an absolute footprint would not be.

    The pointing offset is validated against the engineering line-of-sight in
    ``test_los_alignment.py``, and that the CKs turn about the measured axes is pinned exactly in
    ``tests/unit/test_libera_spice/test_frozen_kernels.py``. What this adds is that the effect
    survives the full chain through to latitude and longitude.
    """
    times = pd.date_range(fixture_gen.WINDOW_START, fixture_gen.WINDOW_END, freq="20ms", inclusive="left")
    ugps_times = spicetime.adapt(times, "iso")

    def geolocate() -> pd.DataFrame:
        lla, _, _ = spatial.compute_ellipsoid_intersection(
            ugps_times,
            sp.obj.Body("LIBERA_RAD", frame=True),
            give_geodetic_output=True,
            give_lat_lon_in_degrees=True,
        )
        return lla

    measured_lla = geolocate()

    # Nominal leg: same source rows, quaternions rebuilt about the ideal axes, and the
    # misalignment-free frame kernel swapped in for the production one.
    nominal_kernels = []
    for builder, field, axis, config_key in (
        (fixture_gen.azimuth_frame, kernel_maker.AZ_ENCODER_FIELD, NOMINAL_AZ_AXIS, "LIBERA_KERNEL_AZ_CK_CONFIG"),
        (fixture_gen.elevation_frame, kernel_maker.EL_ENCODER_FIELD, NOMINAL_EL_AXIS, "LIBERA_KERNEL_EL_CK_CONFIG"),
    ):
        frame, _ = builder()
        kernel_maker.apply_encoder_corrections(frame)
        quaternions = kernel_maker.mechanism_quaternions(frame[field].to_numpy(), axis)
        for name, column in zip(kernel_maker.MECHANISM_QUATERNION_COLUMNS[field], quaternions.T, strict=True):
            frame[name] = column
        nominal_kernels.append(spice_utils.make_kernel(config.get(config_key), short_tmp_path, input_data=frame))

    # Swap only what differs, rather than reloading the whole set: unload the measured mechanism
    # CKs and the production frame kernel, then furnish the nominal ones. The spacecraft ephemeris
    # and attitude stay exactly as furnished for the measured leg, so they cannot contribute to
    # the difference.
    for furnished in spice_utils.ls_kernels():
        if any(tag in Path(furnished.file_name).name for tag in ("AZROT-CK", "ELSCAN-CK")):
            sp.unload(furnished.file_name)
    sp.unload(str(config.get("LIBERA_KERNEL_FRAME")))

    sp.furnsh(str(nominal_frame_kernel))
    for nominal_kernel in nominal_kernels:
        sp.furnsh(str(nominal_kernel))
    nominal_lla = geolocate()

    measured_lat = measured_lla["lat"].to_numpy()
    measured_lon = measured_lla["lon"].to_numpy()
    nominal_lat = nominal_lla["lat"].to_numpy()
    nominal_lon = nominal_lla["lon"].to_numpy()
    comparable = (
        np.isfinite(measured_lat) & np.isfinite(measured_lon) & np.isfinite(nominal_lat) & np.isfinite(nominal_lon)
    )
    assert comparable.sum() > comparable.size // 2, comparable.mean()

    measured_lat, measured_lon = np.deg2rad(measured_lat[comparable]), np.deg2rad(measured_lon[comparable])
    nominal_lat, nominal_lon = np.deg2rad(nominal_lat[comparable]), np.deg2rad(nominal_lon[comparable])
    haversine = (
        1
        - np.cos(measured_lat - nominal_lat)
        + np.cos(nominal_lat) * np.cos(measured_lat) * (1 - np.cos(measured_lon - nominal_lon))
    ) / 2
    shift_km = 2 * constants.WGS84_SEMI_MAJOR_AXIS_KM * np.arcsin(np.sqrt(haversine))

    # The smallest measured tilt of an axis of rotation is 0.065 deg, which moves the nadir
    # footprint by 0.94 km from the ~830 km orbit; samples off nadir move further. A missing or
    # much reduced misalignment leaves some sample short of 0.8 km.
    assert shift_km.min() > 0.8, f"Smallest footprint shift is {shift_km.min():.3f} km"
